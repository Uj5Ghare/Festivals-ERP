const dicts: Record<Lang, Record<DictKey, string>> = { mr, en }

type Vars = Record<string, string | number>
type TFn = (key: DictKey, vars?: Vars) => string

interface LangCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: TFn
}

const Ctx = createContext<LangCtx | null>(null)

function readStored(): Lang {
  try {
    const v = localStorage.getItem('lang')
    return v === 'en' ? 'en' : 'mr'
  } catch {
    return 'mr'
  }
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStored)

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem('lang', l)
    } catch {
      /* private mode: language just won't be remembered */
    }
  }, [])

  const t = useCallback<TFn>(
    (key, vars) => {
      let s = dicts[lang][key]
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
      return s
    },
    [lang],
  )

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): LangCtx {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n outside LangProvider')
  return v
}
